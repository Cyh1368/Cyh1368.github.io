"""Bundle page content so animated navigation also works for file:// previews.

HTML pages remain the source of truth. Run this after editing page content;
the deployment workflow also regenerates the bundle automatically.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
pages = {}
for name in ('index.html', 'research.html', 'contacts.html'):
    html = (root / name).read_text()
    main = re.search(r'<main\b[\s\S]*?</main>', html)
    if not main:
        raise ValueError(f'Missing main element in {name}')
    pages[name] = main.group()

(root / 'src/pages.js').write_text(
    '// Generated by tools/build_page_cache.py; edit the HTML source pages.\n'
    + 'window.SITE_PAGES = '
    + json.dumps(pages, ensure_ascii=False, indent=2)
    + ';\n'
)
